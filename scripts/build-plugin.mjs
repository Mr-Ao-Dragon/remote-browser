/**
 * 构建可分发的 remote-browser 插件包。
 *
 * 产物都落在 plugins/remote-browser/ 内（随包提交，保证 clone 后可直接装）：
 *   server/dist/remote-browser.cjs  esbuild 单文件 bundle，含全部运行时依赖
 *   server/package.json             bundle 的宿主包，playwright-core 运行时会读它取版本
 *   skills/remote-browser/          从仓库 skills/ 同步的 Agent Skill
 *
 * 运行：npm run plugin:build
 * 校验：npm run plugin:check（构建脚本 + Manifest + 冒烟）
 */

import { spawnSync } from "node:child_process";
import { cp, mkdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pluginDir = path.join(root, "plugins", "remote-browser");
const serverDir = path.join(pluginDir, "server");
const bundleFile = path.join(serverDir, "dist", "remote-browser.cjs");
const skillSrc = path.join(root, "skills", "remote-browser");
const skillDest = path.join(pluginDir, "skills", "remote-browser");

function run(label, args) {
  const result = spawnSync(process.execPath, args, { cwd: root, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${label} 失败，退出码 ${result.status}`);
}

function tsc() {
  run("tsc", [path.join(root, "node_modules", "typescript", "bin", "tsc"), "-p", "tsconfig.json"]);
}

function bundle() {
  // 输出 CommonJS：依赖树里有 playwright-core 这类 CJS 代码，用 require / __dirname，
  // 打成 ESM 单文件需要额外垫片；CJS 产物原生就有这些语义，最稳。
  const banner =
    "/* remote-browser MCP server (bundled). Generated by scripts/build-plugin.mjs from src/. Do not edit. */";
  run("esbuild", [
    path.join(root, "node_modules", "esbuild", "bin", "esbuild"),
    path.join(root, "dist", "index.js"),
    "--bundle",
    "--platform=node",
    "--format=cjs",
    "--target=node20",
    "--minify",
    "--define:process.env.NODE_ENV=\"production\"",
    "--legal-comments=eof",
    `--banner:js=${banner}`,
    `--outfile=${bundleFile}`,
    "--log-level=warning",
  ]);
}

/**
 * playwright-core 启动时会按自身包根做两件事：
 *   require(join(__dirname, "..", "package.json"))  读版本号
 *   require(join(__dirname, "..", "browsers.json")) 读浏览器清单
 * bundle 放在 server/dist/ 下，server/ 就是它眼里的包根，这里补齐这两个文件。
 */
async function writeServerManifest() {
  const pwDir = path.join(root, "node_modules", "playwright-core");
  const manifest = {
    name: "remote-browser-server",
    version: "1.0.0",
    private: true,
    main: "dist/remote-browser.cjs",
  };
  await writeFile(path.join(serverDir, "package.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  await cp(path.join(pwDir, "browsers.json"), path.join(serverDir, "browsers.json"));
}

async function syncSkill() {
  await rm(skillDest, { recursive: true, force: true });
  await mkdir(path.dirname(skillDest), { recursive: true });
  // .writing 是写作技能留下的本地版本快照，不属于要分发的 Skill
  await cp(skillSrc, skillDest, {
    recursive: true,
    filter: (src) => path.basename(src) !== ".writing",
  });
}

function kb(bytes) {
  return `${(bytes / 1024).toFixed(0)} KB`;
}

await mkdir(path.dirname(bundleFile), { recursive: true });
tsc();
bundle();
await writeServerManifest();
await syncSkill();

const size = (await stat(bundleFile)).size;
console.log(`\nplugin built: ${path.relative(root, pluginDir)}/`);
console.log(`  server/dist/remote-browser.cjs  ${kb(size)}`);
console.log("  server/package.json             written");
console.log("  skills/remote-browser/          synced from skills/");